def verdict(r):
    if "delta" not in r:
        return "референс"
    lo, hi = r["ci"]
    return "✓" if lo > 0 else ("✗" if hi < 0 else "≈")


def main(path="exp/results.jsonl"):
    rows = [json.loads(line) for line in open(path)]
    groups = {}
    for r in rows:
        groups.setdefault(r["group"], []).append(r)
    for g, rs in groups.items():
        if g == "rank_bug_nulls":
            continue
        print(f"\n#### {g}\n")
        if g == "pool":
            print("| Пул | Потолок | Кандидатов на юзера |\n|---|---|---|")
            for r in rs:
                print(f"| {r['name']} | {r['pool']:.4f} | {r['cands_per_user']} |")
            continue
        print("| Гипотеза | Recall@160 | Δ [95% CI] | Пул | Время | Вердикт | ×100 |\n|---|---|---|---|---|---|---|")
        for r in rs:
            d = f"{r['delta']:+.4f} [{r['ci'][0]:+.4f}; {r['ci'][1]:+.4f}]" if "ci" in r and "delta" in r else (
                f"[{r['ci'][0]:.4f}; {r['ci'][1]:.4f}]" if "ci" in r else "—")
            pool = r.get("pool1000", r.get("pool", ""))
            print(f"| {r['name']} | {r['recall']:.4f} | {d} | {pool} | {r['sec']:.0f} с | {VERDICT.get(r['name'], verdict(r))} | {SCALE.get(r['name'], '—')} |")


if __name__ == "__main__":
    main(*sys.argv[1:])
